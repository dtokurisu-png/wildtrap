import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const gpu=readFileSync(new URL('../editor-terrain-gpu-layers.mjs',import.meta.url),'utf8');
const renderer=readFileSync(new URL('../editor-terrain-texture-renderer.mjs',import.meta.url),'utf8');
assert.match(gpu,/texture2D\(baseTexture,sourceUV\)/,'Base must sample native PNG on GPU');
assert.match(gpu,/vTerrainXZ\/630\.0\*repeats/,'Base repeat scale must be preserved');
assert.match(gpu,/new THREE\.Texture\(fullResolutionSource\(image\)\)/,'Base must use source PNG, not baked 768px bitmap');
assert.match(gpu,/new THREE\.CanvasTexture\(canvas\)/,'Canvas must only be zone alpha mask');
assert.doesNotMatch(gpu,/sparsePatch|detailMap[123]|smoothNoise/,'Unstable random complements and shading must be disabled');
assert.match(gpu,/new THREE\.Mesh\(terrain\.geometry,shader\)/,'GPU ground must use terrain geometry');
assert.match(gpu,/entry\.mesh\.geometry=terrain\.geometry/,'GPU ground must follow geometry edits');
assert.doesNotMatch(gpu,/editorOnly\s*=\s*true/,'Base must remain visible in Play');
assert.match(renderer,/gpuLayers\.build\(/,'GPU base renderer must remain connected');
assert.match(renderer,/\['ground','cliff'\]/,'Only base and cliff textures should load in safe mode');
assert.match(renderer,/buildCliffs\(\);apply\(\)/,'Cliff renderer should remain connected');
assert.doesNotMatch(renderer,/surfaceMap\.needsUpdate=true/,'Old baked 768px bitmap must not be uploaded');
assert.equal(630/200,3.15,'Saved repeat count must preserve tile size');
console.log('PASS: Safe terrain renders native base and cliff only, preserving repeat scale and terrain geometry');
